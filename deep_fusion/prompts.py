@mcp.prompt("analyze-cycle-position")
def prompt_analyze_cycle_position():
    """【周期定位专项】判断当前宏观经济周期阶段及对投资的系统性影响"""
    return """
    你现在是一名宏观策略分析师。请执行完整的周期定位分析：

    ## 基钦周期（库存周期）定位
    1. 获取以下宏观数据（月度）：
       - 工业增加值同比增速
       - 工业企业产成品存货同比增速
    2. 对数据进行3月移动平均平滑。
    3. 结合 `skill://investment/cycle/kitchin-cycle` 中的四阶段框架：
       - 绘制象限图（X=工业增加值增速，Y=产成品存货增速）
       - 标注近24个月轨迹，判断当前所处阶段
    4. 解读当前阶段对权益投资的宏观含义。

    ## 朱格拉周期（投资周期）定位
    5. 获取以下宏观数据：
       - 固定资产投资完成额:累计同比
       - GDP:不变价当季同比
       - 辅助：制造业PMI、M2/社融、企业中长期贷款
    6. 结合 `skill://investment/cycle/juglar-cycle` 判断当前景气位置。
    7. 解读当前阶段对行业配置的指导意义。

    ## 可选延伸
    8. 调用 `merrill_lynch` 进行美林时钟定位。
    9. 调用 `kondratiev_wave` 获取长波技术周期位置。

    ## 综合输出
    10. 明确当前周期综合环境：顺风（Δ_cycle>0）/ 中性（Δ≈0）/ 逆风（Δ<0）。
    11. 指出在此周期阶段下应着重关注的行业类型与风险类型。
    12. 给出未来6-12个月的关键宏观跟踪指标及可能触发周期阶段转换的信号。
    """


