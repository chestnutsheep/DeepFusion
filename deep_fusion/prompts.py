@mcp.prompt("full-investment-report")
def prompt_full_investment_report(symbol: str):
    """【综合投研报告】一键生成完整投资分析报告"""
    return f"""
    你现在是首席投资分析师。请为 **{symbol}** 生成一份完整的投资分析报告，严格遵循专业投研框架：

    ## 报告结构

    ### 一、投资概要
    - 核心投资逻辑一句话总结
    - 当前评级（强烈推荐/推荐/中性/回避）
    - 目标价区间与当前价格偏离度

    ### 二、周期定位摘要
    - 基钦周期阶段及含义
    - 朱格拉周期阶段及含义
    - 综合周期环境判断（Δ_cycle符号及弹性系数β）
    - 可选：康波/美林时钟定位

    ### 三、行业比较分析
    - 估值相对位置（PE/PB vs 行业中值，历史分位数）
    - 成长性相对位置（超额营收增速，α/β剥离）
    - 杜邦分解对比（ROE归因瀑布图核心发现）
    - 规模与市场地位定位

    ### 四、个股质量深度
    - 收入结构拆解（业务构成、依赖度、稳定性）
    - 毛利率驱动因素分析（历史趋势线、行业对比）
    - 利润质量评估（非经常性损益占比、现金流匹配度）
    - 营运效率诊断（应收/存货周转趋势）

    ### 五、市场行为印证
    - 机构行为：北向资金、十大股东变动、机构调研
    - 内部人行为：高管增减持动向
    - 杠杆情绪：融资融券余额趋势
    - 舆情环境：新闻情感与社交媒体热度

    ### 六、估值与情景分析
    - 相对估值：PE/PB/PEG/EV-EBITDA 与行业及历史对比
    - 绝对估值：DCF关键假设与敏感性分析
    - 情景分析：
      · 乐观情景（概率、触发条件、目标价）
      · 基准情景（概率、核心假设、目标价）
      · 悲观情景（概率、风险因素、目标价）
    - 赔率计算

    ### 七、核心证据矩阵与结论
    - 正面证据汇总
    - 反面证据汇总
    - 综合印证结论（强烈印证/部分印证/无法判断/强烈驳斥）
    - 置信度评估

    ### 八、投资策略与跟踪计划
    - 建议仓位（参考信念-仓位映射矩阵）
    - 关键验证节点与指标阈值
    - 纠错机制与止损条件
    - 后续重点关注事件清单

    请确保所有分析均结合 `skill://investment/*` 系列资源中的方法论框架进行阐述。
    """
