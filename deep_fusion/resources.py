@mcp.resource("skill://investment/fundamental/internal-inspection")
def resource_fundamental_inspection():
    """提供财务基本面内部检验SOP"""
    return """
    财务基本面内部检验 SOP:
    - 盈利现金保障倍数 
       - 持续 > 1：利润含金量高，造血能力强
       - 持续 < 0.7：利润可能只是"纸面富贵"，需结合应收账款周转天数判断
    - 营收现金回收率 = 销售商品提供劳务收到的现金 / 营业收入
       - 持续 < 1：收入确认可能偏激进，或回款周期在拉长
    - 应收账款周转天数 = 365 / (营业收入 / 平均应收账款)
       - 连续上升：对下游议价能力可能变弱，或通过放宽信用政策刺激销售
    - 存货周转天数 = 365 / (营业成本 / 平均存货)
       - 连续上升：产品可能出现滞销，或管理层对需求过于乐观导致备货过度
    - 毛利率趋势
       - 连续下滑：产品竞争力下降、成本上升、或行业竞争加剧
       - 毛利率上升但周转天数同步大幅上升：可能是以放宽信用或压货为代价的短期增长

    ## 行动步骤
    1. 获取目标公司过去3-5年的年度及季度财务数据（利润表、资产负债表、现金流量表）
    2. 提取以下指标绘制时间序列趋势图：
       - 营收同比增长率
       - 毛利率 = (营业收入 - 营业成本) / 营业收入
       - 净利率 = 净利润 / 营业收入
       - ROE = 净利润 / 平均净资产
       - 盈利现金保障倍数、营收现金回收率
       - 应收账款周转天数、存货周转天数
    3. 观察各指标的变化方向与交叉验证
    """


@mcp.resource("skill://investment/fundamental/industry-comparison")
def resource_industry_comparison():
    """提供行业相对位置比较SOP"""
    return """
    行业相对位置比较 SOP:

    1. 超额营收增速 = 个股营收增速 - 行业平均营收增速
       - 持续为正且位于+1σ上方：公司在行业中具备显著竞争优势，市场份额提升
       - 为正但估值折价扩大：市场可能尚未充分反映成长性，存在预期差
    2. 超额ROE = 个股ROE - 行业平均ROE
       - 差值主要来自销售净利率：拥有品牌或技术壁垒，盈利质量较高
       - 差值主要来自权益乘数（高杠杆）：高回报依赖财务风险，下行期脆弱性高
    3. 相对PE折溢价 = (个股PE - 行业中值PE) / 行业中值PE × 100%
    4. 杜邦因子差值 = 个股因子值 - 行业平均因子值
       - ROE低于行业但总资产周转率低：若处于重资产扩张期可接受，成熟期则反映效率问题
    5. 超额指标在±1σ带内波动：个股表现与行业整体同步，缺乏显著α特征

    行动步骤：
    1. 确定可比行业（申万二级或三级行业）
    2. 获取行业均值/中位数及标准差（σ）：
       - 营收增长率、ROE、PE、PB
       - 杜邦分析三因子（销售净利率、总资产周转率、权益乘数）
    3. 计算个股超额/差值序列（连续多期），绘制时间序列图并标注±1σ波动带
    """


