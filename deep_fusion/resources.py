@mcp.resource("skill://investment/visualization/core-formula")
def resource_core_formula():
    """提供核心估值-预期修正公式"""
    return """
    核心估值-预期修正公式:

    P_fair = f(E_fund) × λ_sentiment × e^(β × Δ_cycle)

    ## 参数解析
    - P_fair：理论公允价格区间
    - E_fund：基本面内生价值基础（由收入结构、毛利率趋势、ROIC-WACC差值量化）
    - λ_sentiment：市场情绪乘数因子
      · λ > 1：情绪乐观，价格获得溢价
      · λ < 1：情绪悲观，价格承受折价
      · λ = 1：情绪中性，价格向基本面回归
    - Δ_cycle：周期相位偏离系数
      · Δ > 0：周期上行扩张阶段，对估值容忍度提升
      · Δ < 0：周期下行收缩阶段，需施加更高风险折价
    - β：个股周期敏感系数（周期性行业β值高，防御性行业β值低）

    ## 分析结论推导
    - P_fair 显著高于 P_market，且 λ<1、Δ<0：
      市场因短期悲观情绪和周期低谷对优质基本面资产进行了错误折价，构成潜在投资机会
    - P_fair 低于 P_market，且 λ>1、Δ>0：
      当前价格已过度反映乐观预期和周期红利，存在估值泡沫风险
    """


